CLOSE_BRIEFS = [
    "I need {noun}. Budget is under ${budget}.",
    "Can you buy me {noun}? Keep it under ${budget}.",
]


def close_products(cat: dict) -> list[dict]:
    """Template products. Review counts and descriptions are reassigned per shelf by the generator."""
    ref = cat["products"][cat["close_reference"]]
    price = round(cat["budget"] * 0.8)
    brands = [prod["brand"] for prod in cat["products"]]
    return [
        p(brands[i], f"{CLOSE_LINES[i]} {cat['close_title']}", price, CLOSE_RATING, 1000,
          dict(ref["specs"]), CLOSE_DESCRIPTIONS[i])
        for i in range(6)
    ]


def close_briefs(cat: dict) -> list[str]:
    return [b.format(noun=cat["noun"], budget=cat["budget"]) for b in CLOSE_BRIEFS]
